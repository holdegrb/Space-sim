#!/usr/bin/env python3
"""Generates lib/ui/ship_art.dart from the ship design canvas's SVG <symbol>s.

Usage (the design files are copies of the canvas's artboards):
    python3 tool/gen_ship_art.py design/player_ships.dc.html \
        design/enemy_ships.dc.html > lib/ui/ship_art.dart
    dart format lib/ui/ship_art.dart

Supports what the designs use: <path d> with absolute M/L/C/Z, <rect> (rx),
<circle>, <ellipse>, each with a hex fill and optional opacity.
"""
import re
import sys


def num(v):
    f = float(v)
    return repr(f) if f != int(f) else f"{int(f)}.0"


def color(fill):
    fill = fill.strip()
    if fill == 'none':
        return None
    h = fill.lstrip('#')
    if len(h) == 3:
        h = ''.join(c * 2 for c in h)
    assert len(h) == 6, fill
    return f"0xFF{h.upper()}"


def path_ops(d):
    toks = re.findall(r'[MLCZ]|-?\d*\.?\d+', d)
    out, i, cmd = [], 0, None
    while i < len(toks):
        t = toks[i]
        if t in 'MLCZ':
            cmd = t
            i += 1
            if cmd == 'Z':
                out.append('..close()')
            continue
        n = {'M': 2, 'L': 2, 'C': 6}[cmd]
        args = ', '.join(num(x) for x in toks[i:i + n])
        out.append({'M': '..moveTo', 'L': '..lineTo', 'C': '..cubicTo'}[cmd] + f'({args})')
        i += n
        if cmd == 'M':
            cmd = 'L'  # implicit lineto after moveto
    assert not re.search(r'[a-zHVSQTA]', d), f'unsupported path command in {d}'
    return 'Path()' + ''.join(out)


def attrs(s):
    return dict(re.findall(r'([\w-]+)="([^"]*)"', s))


def shape(tag, a):
    c = color(a.get('fill', '#000000'))
    if c is None:
        return None
    op = num(a.get('opacity', '1'))
    if tag == 'path':
        p = path_ops(a['d'])
    elif tag == 'rect':
        x, y, w, h = (float(a[k]) for k in ('x', 'y', 'width', 'height'))
        rx = float(a.get('rx', 0))
        p = (f'Path()..addRRect(RRect.fromLTRBR({num(x)}, {num(y)}, {num(x + w)}, '
             f'{num(y + h)}, const Radius.circular({num(rx)})))')
    elif tag == 'circle':
        p = (f'Path()..addOval(Rect.fromCircle(center: const Offset({num(a["cx"])}, '
             f'{num(a["cy"])}), radius: {num(a["r"])}))')
    elif tag == 'ellipse':
        p = (f'Path()..addOval(Rect.fromCenter(center: const Offset({num(a["cx"])}, '
             f'{num(a["cy"])}), width: {num(2 * float(a["rx"]))}, '
             f'height: {num(2 * float(a["ry"]))}))')
    else:
        raise SystemExit(f'unsupported element <{tag}>')
    return f'    ArtShape(const Color({c}), {op}, {p}),'


def camel(sym_id):
    parts = re.sub(r'^(ship|enemy)-', '', sym_id).split('-')
    return parts[0] + ''.join(p.title() for p in parts[1:])


print('// GENERATED by tool/gen_ship_art.py from the ship design canvas. Do not edit by hand.')
print('// ignore_for_file: prefer_const_constructors')
print()
print("import 'package:flutter/painting.dart';")
print()
print("import 'ship_art_types.dart';")
print()
names = []
for f in sys.argv[1:]:
    src = open(f).read()
    for sid, vb, body in re.findall(r'<symbol id="([^"]+)" viewBox="([^"]+)">(.*?)</symbol>', src, re.S):
        _, _, w, h = (float(v) for v in vb.split())
        name = camel(sid)
        kind = 'player' if sid.startswith('ship-') else 'enemy'
        names.append((kind, sid, name))
        print(f'/// `{sid}`')
        print(f'final {name}Art = ShipArt({num(w)}, {num(h)}, [')
        for tag, a in re.findall(r'<(path|rect|circle|ellipse)\s([^>]*?)/?>', body):
            line = shape(tag, attrs(a))
            if line:
                print(line)
        print(']);')
        print()
